_C = [(t[0], re.compile(t[3]), re.compile(t[4])) for t in TYPES]


def classify(kind, folder_cat, name, menus, review_menus):
    """kind: 네이버 업종, folder_cat: 저장 목록 업종(음식점/BAR/카페), menus/review_menus: 이름 리스트."""
    kind = kind or ""
    signature = review_menus[:3] + menus[:3]  # 대표 음식만 본다 (사이드 메뉴 제외)
    scores = {}
    for tid, kre, mre in _C:
        s = 0
        if kind and kre.search(kind):
            s += 3
        if kre.search(name):
            s += 2
        s += sum(1 for m in signature if m and mre.search(m))
        if review_menus and mre.search(review_menus[0]):
            s += 1  # 후기에서 가장 많이 언급된 메뉴는 한 번 더 쳐준다
        if s:
            scores[tid] = s
    if folder_cat == "BAR" and "bar" not in scores and "izakaya" not in scores and "pocha" not in scores:
        scores["bar"] = 2
    if folder_cat == "카페" and "cafe" not in scores:
        scores["cafe"] = 2
    # 업종이 '한식'뿐이고 다른 대표 메뉴 유형이 있으면 한식은 뺀다
    if "korean" in scores and len(scores) > 1 and scores["korean"] <= 3:
        scores.pop("korean")
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    out = [t for t, s in ranked if s >= 2][:3]
    if not out and ranked:
        out = [ranked[0][0]]
    return out
